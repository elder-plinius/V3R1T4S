#!/usr/bin/env python3
"""
Requirement (c) Verifier: Explicit Quantum Circuit Synthesis ({CNOT, T, S, Z, CZ})
and Exact Path-Sum / Phase-Polynomial + Full Statevector Equivalence Verification.

For each claimed Waring (T-count) decomposition A in {0, 1}^{r x n} (n <= 30 qubits):
  1. Synthesizes an explicit Clifford+T quantum circuit C over {CNOT, T, S, Z, CZ}:
     - Input basis change CNOT network implementing x -> B x (where B = A_bco^{-1},
       or B = I_n for 0732 and 0733).
     - Parity CNOT ladder + r single-qubit T = diag(1, exp(i*pi/4)) gates, one per
       row p^(q) of the Waring matrix A (total T-count = r, zero ancilla qubits).
     - Exact Clifford phase correction layer over {S, Z, CZ} cancelling the linear
       and quadratic Z_8 residuals generated by sum_{q=1}^r (p^(q)(x) mod 2):
         * Because every column sum M_i = sum_q A_{q,i} is EVEN (M_i = 2 m_i),
           the linear correction -M_i x_i mod 8 = 2(-m_i mod 4) x_i is implemented
           purely by single-qubit Clifford S = T^2 and Z = T^4 gates (0 T-gates).
         * Because every pair sum Q_{ij} = sum_q A_{q,i} A_{q,j} is EVEN (Q_{ij} = 2 s_{ij}),
           the quadratic correction +2 Q_{ij} x_i x_j mod 8 = 4(s_{ij} mod 2) x_i x_j
           is implemented purely by two-qubit Clifford CZ = diag(1, 1, 1, -1) gates (0 T-gates).
     - Inverse basis change CNOT network implementing B^{-1}.
  2. Simulates the synthesized gate-level circuit symbolically in Z_8[x_0, ..., x_{n-1}]/(x_i^2 - x_i)
     (exact path-sum / phase-polynomial simulation) AND verifies that:
     - All n linear coefficients match 0 mod 8,
     - All n(n-1)/2 quadratic coefficients match 0 mod 8,
     - All n(n-1)(n-2)/6 cubic coefficients match 4 * T_orig[i,j,k] mod 8.
  3. Performs an exact exhaustive 2^21 = 2,097,152-state full diagonal statevector
     equivalence check on 0105 (CSLA MUX_3, n=21) and an exact 2^20 = 1,048,576-state
     direct circuit + oracle evaluation on 0732 (GF(2^9) Mult, n=27) and 0733 (GF(2^10) Mult, n=30).
"""
