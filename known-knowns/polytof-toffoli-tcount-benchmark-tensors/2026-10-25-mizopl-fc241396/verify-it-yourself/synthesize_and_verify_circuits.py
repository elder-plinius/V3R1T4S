def gf2_inv(A):
    """Invert an n x n binary matrix over GF(2)."""
    n = A.shape[0]
    M = np.hstack([A.astype(np.uint8) & 1, np.eye(n, dtype=np.uint8)])
    for col in range(n):
        pivot = -1
        for row in range(col, n):
            if M[row, col]:
                pivot = row
                break
        if pivot == -1:
            raise ValueError("Matrix is singular over GF(2)")
        if pivot != col:
            M[[col, pivot]] = M[[pivot, col]]
        for row in range(n):
            if row != col and M[row, col]:
                M[row] ^= M[col]
    return M[:, n:]


def load_triples(path):
    arr = np.load(path)
    n = int(arr[0, 0])
    triples = [tuple(int(x) for x in row) for row in arr[1:]]
    return n, triples


def synthesize_clifford_t_circuit(A, transform_mat=None):
    """
    Given Waring parity matrix A of shape (r, n) over {0, 1} and optional BCO
    transform matrix transform_mat of shape (n, n), synthesize an explicit
    gate-by-gate Clifford+T circuit implementing the cubic phase polynomial.

    Returns a dictionary containing:
      - t_count: exact number of T gates in the synthesized circuit (= r)
      - s_count: number of Clifford S / S^dagger gates
      - z_count: number of Clifford Z gates
      - cz_count: number of Clifford CZ gates
      - cnot_count: number of CNOT gates in the parity + basis synthesis
      - linear_phases_mod8: length-n array of single-qubit Z_8 phase multiples (all even)
      - cz_pairs: list of (i, j) qubit pairs receiving a CZ gate
      - parity_gates: list of CNOT ladders + T gate target wires for each of the r parities
    """
    A = (A.astype(np.int64) & 1)
    r, n = A.shape

    # 1. Verify column sums and pair sums are all even (so 0 extra T gates are needed!)
    col_sums = A.sum(axis=0)  # length n
    pair_sums = (A[:, :, None] * A[:, None, :]).sum(axis=0)  # (n, n), avoids macOS Accelerate @ bug
    odd_cols = int(np.sum(col_sums % 2))
    odd_pairs = int(np.sum( np.triu(pair_sums, k=1) % 2 ))
    if odd_cols != 0 or odd_pairs != 0:
        raise ValueError(f"Unexpected odd linear ({odd_cols}) or quadratic ({odd_pairs}) sum!")

    # 2. Synthesize each parity row p^(q) into CNOT fan-in + T(target) + CNOT uncompute
    parity_gates = []
    cnot_count = 0
    for q in range(r):
        supp = [int(i) for i in np.flatnonzero(A[q])]
        target = supp[0]
        controls = supp[1:]
        # CNOT fan-in to target, T gate on target, CNOT fan-out uncompute
        cnot_count += 2 * len(controls)
        parity_gates.append({
            "term_index": q,
            "support": supp,
            "target_qubit": target,
            "cnot_controls": controls,
            "gate": "T",
        })

    # 3. Synthesize exact Clifford correction layer over {S, Z, CZ}:
    # Expansion of sum_{q=1}^r p^(q)(y) mod 8 on y in {0, 1}^n:
    #   p^(q)(y) = sum_i A_{q,i} y_i - 2 sum_{i<j} A_{q,i} A_{q,j} y_i y_j + 4 sum_{i<j<k} A_{q,i} A_{q,j} A_{q,k} y_i y_j y_k (mod 8)
    # Therefore, to leave ONLY 4 sum_{i<j<k} T_{ijk} y_i y_j y_k (mod 8):
    #   - Qubit i receives phase (-col_sums[i]) mod 8 in {0, 2, 4, 6}:
    #       2 -> S, 4 -> Z, 6 -> S^dagger (0 T-gates!)
    #   - Pair (i, j) (i < j) receives phase (+2 * pair_sums[i, j]) mod 8 in {0, 4}:
    #       4 -> CZ(i, j) (0 T-gates!)
    linear_phases_mod8 = [int((-col_sums[i]) % 8) for i in range(n)]
    s_count = sum(1 for c in linear_phases_mod8 if c in (2, 6))
    z_count = sum(1 for c in linear_phases_mod8 if c == 4)

    cz_pairs = []
    for i in range(n):
        for j in range(i + 1, n):
            quad_phase = int((2 * pair_sums[i, j]) % 8)
            if quad_phase == 4:
                cz_pairs.append((i, j))
            elif quad_phase != 0:
                raise ValueError(f"Non-Clifford quadratic phase {quad_phase} at ({i},{j})")

    # 4. Count basis-change CNOTs if transform_mat != I_n via Gaussian elimination
    basis_cnots = 0
    if transform_mat is not None and not np.array_equal(transform_mat, np.eye(n, dtype=np.uint8)):
        M = transform_mat.astype(np.uint8).copy()
        for col in range(n):
            pivot = [row for row in range(col, n) if M[row, col]][0]
            if pivot != col:
                M[[col, pivot]] = M[[pivot, col]]
                basis_cnots += 3
            for row in range(n):
                if row != col and M[row, col]:
                    M[row] ^= M[col]
                    basis_cnots += 1
        cnot_count += 2 * basis_cnots  # compute y = A^{-1} x and uncompute

    return {
        "n_qubits": n,
        "t_count": r,
        "s_count": s_count,
        "z_count": z_count,
        "cz_count": len(cz_pairs),
        "cnot_count": cnot_count,
        "basis_cnot_count": 2 * basis_cnots,
        "linear_phases_mod8": linear_phases_mod8,
        "cz_pairs": cz_pairs,
        "parity_gates": parity_gates,
        "A_matrix": A,
    }


def verify_symbolic_path_sum_z8(circuit, orig_triples, transform_mat=None):
    """
    Exact symbolic path-sum / phase-polynomial verification in Z_8[x_0, ..., x_{n-1}]/(x_i^2 - x_i).
    Simulates the synthesized circuit gate-by-gate on the multilinear phase polynomial in Z_8:
      1. Starts at Phi(y) = 0 in Z_8[y_0, ..., y_{n-1}].
      2. For each of the r synthesized CNOT+T+CNOT gadgets:
         adds p^(q)(y) = sum_i p_i y_i - 2 sum_{i<j} p_i p_j y_i y_j + 4 sum_{i<j<k} p_i p_j p_k y_i y_j y_k (mod 8).
      3. Applies the synthesized S/Z single-qubit gates and CZ two-qubit gates.
      4. Pulls back along the basis change y = A_bco^{-1} x (if transform_mat != I_n).
      5. Verifies that every linear coefficient is 0 mod 8, every quadratic coefficient is 0 mod 8,
         and every cubic coefficient equals 4 * T_orig[i,j,k] mod 8!
    """
    n = circuit["n_qubits"]
    A = circuit["A_matrix"]
    r = circuit["t_count"]

    # Accumulate Z_8 multilinear polynomial in y-coordinates
    lin_y = np.zeros(n, dtype=np.int64)
    quad_y = np.zeros((n, n), dtype=np.int64)
    cub_y = np.zeros((n, n, n), dtype=np.int64)

    # Step 1: Simulate each CNOT-ladder + T-gate gadget in Z_8
    for q in range(r):
        supp = circuit["parity_gates"][q]["support"]
        for i in supp:
            lin_y[i] = (lin_y[i] + 1) % 8
        for a in range(len(supp)):
            i = supp[a]
            for b in range(a + 1, len(supp)):
                j = supp[b]
                quad_y[i, j] = (quad_y[i, j] - 2) % 8
                for c in range(b + 1, len(supp)):
                    k = supp[c]
                    cub_y[i, j, k] = (cub_y[i, j, k] + 4) % 8

    # Step 2: Simulate single-qubit Clifford S / Z correction gates
    for i, phase in enumerate(circuit["linear_phases_mod8"]):
        lin_y[i] = (lin_y[i] + phase) % 8

    # Step 3: Simulate two-qubit Clifford CZ correction gates
    for (i, j) in circuit["cz_pairs"]:
        quad_y[i, j] = (quad_y[i, j] + 4) % 8

    lin_ok = bool(np.all(lin_y == 0))
    quad_ok = bool(np.all(quad_y == 0))

    # Step 4: Pull back cubic terms along y = A_bco^{-1} x (since lin_y == 0 and quad_y == 0,
    # pullback of 4 * sum_{i<j<k} C_{ijk} y_i y_j y_k along a GF(2)-linear map y = B x
    # has zero linear and zero quadratic terms in Z_8 because 4 * u^2 * v = 4 * u * v in Z_8,
    # and in a symmetric cubic tensor over F_2 every pair (i, i, j) occurs 3! / 2! = 3 times
    # or Wait: let's verify how BCO transform acts on phase polynomials!).
    # Wait: in polytof, BCO transforms the cubic tensor T_bco(y) = T_orig(A_bco y),
    # and any quadratic phase generated by x_i^2 = x_i during basis change is pure Clifford (4 x_i x_j = CZ)!
    cub_bco_triples = set()
    for i in range(n):
        for j in range(i + 1, n):
            for k in range(j + 1, n):
                if cub_y[i, j, k] == 4:
                    cub_bco_triples.add((i, j, k))
                elif cub_y[i, j, k] != 0:
                    return False, f"Unexpected cubic phase {cub_y[i,j,k]} at {(i,j,k)}"

    # Pull back cub_y to original coordinates x via y = B x (where B = A_bco^{-1})
    if transform_mat is not None and not np.array_equal(transform_mat, np.eye(n, dtype=np.uint8)):
        # T_orig[a,b,c] = T_bco(A_bco x): let's push forward cub_bco by A_bco
        M = transform_mat.astype(np.uint8)
        T_dense = np.zeros((n, n, n), dtype=np.uint8)
        for (i, j, k) in cub_bco_triples:
            for p in ((i,j,k), (i,k,j), (j,i,k), (j,k,i), (k,i,j), (k,j,i)):
                T_dense[p] = 1
        # Apply M: T_orig = apply_inverse_transform(T_bco, M)
        T1 = np.zeros((n, n, n), dtype=np.uint8)
        for a in range(n):
            idx = np.flatnonzero(M[a])
            if len(idx):
                T1[a] = np.bitwise_xor.reduce(T_dense[idx], axis=0)
        T2 = np.zeros((n, n, n), dtype=np.uint8)
        for b in range(n):
            idx = np.flatnonzero(M[b])
            if len(idx):
                T2[:, b, :] = np.bitwise_xor.reduce(T1[:, idx, :], axis=1)
        T3 = np.zeros((n, n, n), dtype=np.uint8)
        for c in range(n):
            idx = np.flatnonzero(M[c])
            if len(idx):
                T3[:, :, c] = np.bitwise_xor.reduce(T2[:, :, idx], axis=2)
        rec_triples = set()
        for i in range(n):
            for j in range(i + 1, n):
                for k in range(j + 1, n):
                    if T3[i, j, k]:
                        rec_triples.add((i, j, k))
    else:
        rec_triples = cub_bco_triples

    cub_ok = (rec_triples == set(orig_triples))
    return (lin_ok and quad_ok and cub_ok), {
        "linear_zero_mod8": lin_ok,
        "quadratic_zero_mod8": quad_ok,
        "cubic_exact_mod8": cub_ok,
        "reconstructed_nnz": len(rec_triples),
        "target_nnz": len(orig_triples),
    }


def verify_exhaustive_statevector_21q(circuit, bco_triples):
    """
    Exhaustive 2^21 = 2,097,152-state statevector / phase-table check for n=21 (0105 CSLA MUX_3).
    Evaluates the synthesized circuit gate-by-gate on all 2^21 basis states simultaneously
    using vectorized bit-parallel blocks of 2^21 uint8 Z_8 phases, and compares against
    the target unitary exp(i * pi/4 * 4 * sum_{i<j<k} T_{ijk} y_i y_j y_k) across all 2,097,152 states!
    """
    n = circuit["n_qubits"]
    assert n == 21
    num_states = 1 << n  # 2,097,152
    states = np.arange(num_states, dtype=np.uint32)
    bits = [(states >> i).astype(np.uint8) & 1 for i in range(n)]

    # 1. Simulate synthesized circuit: r CNOT-parity + T gates, then S/Z gates, then CZ gates
    phase_synth = np.zeros(num_states, dtype=np.uint8)
    for pg in circuit["parity_gates"]:
        p = np.zeros(num_states, dtype=np.uint8)
        for i in pg["support"]:
            p ^= bits[i]
        phase_synth = (phase_synth + p) & 7

    for i, c in enumerate(circuit["linear_phases_mod8"]):
        if c:
            phase_synth = (phase_synth + c * bits[i]) & 7

    for (i, j) in circuit["cz_pairs"]:
        phase_synth = (phase_synth + 4 * (bits[i] & bits[j])) & 7

    # 2. Evaluate target benchmark phase polynomial on all 2^21 states
    phase_target = np.zeros(num_states, dtype=np.uint8)
    for (i, j, k) in bco_triples:
        phase_target = (phase_target + 4 * (bits[i] & bits[j] & bits[k])) & 7

    mismatches = int(np.sum(phase_synth != phase_target))
    return mismatches == 0, {
        "n_qubits": n,
        "states_checked": num_states,
        "mismatches": mismatches,
        "fidelity": 1.0 if mismatches == 0 else 0.0,
    }


def verify_gf2k_multiplier_oracle(circuit, k, prim_exps, n_samples=1 << 20):
    """
    Direct circuit-vs-oracle statevector equivalence check for GF(2^k) multiplication
    (0732: k=9, n=27 qubits; 0733: k=10, n=30 qubits) across 2^20 = 1,048,576 states!
    Compares the synthesized r-T-gate circuit phase exp(i*pi/4 * Phi_synth(a, b, c))
    directly against the algebraic GF(2^k) field multiplication oracle (-1)^{<a * b, c>}!
    """
    n = circuit["n_qubits"]
    assert n == 3 * k
    rng = np.random.default_rng(20261025 + k)
    mask = (1 << k) - 1

    # Generate 2^20 = 1,048,576 inputs (a, b, c) in GF(2^k)^3
    a_vals = rng.integers(0, 1 << k, size=n_samples, dtype=np.uint32)
    b_vals = rng.integers(0, 1 << k, size=n_samples, dtype=np.uint32)
    c_vals = rng.integers(0, 1 << k, size=n_samples, dtype=np.uint32)

    # Extract 3k bit arrays of length n_samples
    bits = []
    for i in range(k):
        bits.append(((a_vals >> i) & 1).astype(np.uint8))
    for i in range(k):
        bits.append(((b_vals >> i) & 1).astype(np.uint8))
    for i in range(k):
        bits.append(((c_vals >> i) & 1).astype(np.uint8))

    # 1. Evaluate synthesized Clifford+T circuit gate-by-gate on all 1,048,576 states
    phase_synth = np.zeros(n_samples, dtype=np.uint8)
    for pg in circuit["parity_gates"]:
        p = np.zeros(n_samples, dtype=np.uint8)
        for i in pg["support"]:
            p ^= bits[i]
        phase_synth = (phase_synth + p) & 7

    for i, c in enumerate(circuit["linear_phases_mod8"]):
        if c:
            phase_synth = (phase_synth + c * bits[i]) & 7

    for (i, j) in circuit["cz_pairs"]:
        phase_synth = (phase_synth + 4 * (bits[i] & bits[j])) & 7

    # 2. Evaluate algebraic GF(2^k) multiplication oracle a * b mod f(x) on all 1,048,576 states
    mod_poly = 0
    for e in prim_exps:
        if e < k:
            mod_poly |= (1 << e)
    prod = np.zeros(n_samples, dtype=np.uint32)
    aa = a_vals.copy()
    bb = b_vals.copy()
    for _ in range(k):
        take = (bb & 1) != 0
        prod[take] ^= aa[take]
        carry = (aa & (1 << (k - 1))) != 0
        aa = (aa << 1) & mask
        aa[carry] ^= mod_poly
        bb >>= 1

    # Inner product <a * b, c> mod 2 -> phase 4 * <a * b, c> mod 8
    inner = np.zeros(n_samples, dtype=np.uint8)
    anded = prod & c_vals
    for i in range(k):
        inner ^= ((anded >> i) & 1).astype(np.uint8)
    phase_oracle = (4 * inner) & 7

    mismatches = int(np.sum(phase_synth != phase_oracle))
    return mismatches == 0, {
        "k": k,
        "n_qubits": n,
        "states_checked": n_samples,
        "mismatches": mismatches,
        "exact_oracle_match": (mismatches == 0),
    }


