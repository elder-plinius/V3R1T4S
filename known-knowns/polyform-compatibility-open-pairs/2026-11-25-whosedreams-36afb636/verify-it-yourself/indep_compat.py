#!/usr/bin/env python3
"""Independent small-k check for heptiamonds M and X (standard library only).

Written from the definition, with its own triangle coordinates; it shares no code with the SAT encoder.
A triangle is (a, b, c) with a + b + c in {1, 2} (1 = down, 2 = up). Edge neighbours of an up triangle are
(a-1,b,c), (a,b-1,c), (a,b,c-1); of a down triangle (a+1,b,c), (a,b+1,c), (a,b,c+1).
The 12 lattice symmetries fixing the origin vertex structure are generated by the cyclic shift (a,b,c)->(b,c,a),
the swap (a,b,c)->(b,a,c) and the point reflection (a,b,c)->(1-a,1-b,1-c); translations add (u,v,w) with u+v+w=0.
"""
import itertools, sys

def nbrs(t):
    a, b, c = t
    if a + b + c == 2:
        return [(a - 1, b, c), (a, b - 1, c), (a, b, c - 1)]
    return [(a + 1, b, c), (a, b + 1, c), (a, b, c + 1)]

def _gens():
    rot = lambda t: (t[1], t[2], t[0])
    swp = lambda t: (t[1], t[0], t[2])
    inv = lambda t: (1 - t[0], 1 - t[1], 1 - t[2])
    maps = []
    for r in range(3):
        for s in range(2):
            for i in range(2):
                def f(t, r=r, s=s, i=i):
                    for _ in range(r):
                        t = rot(t)
                    if s:
                        t = swp(t)
                    if i:
                        t = inv(t)
                    return t
                maps.append(f)
    return maps
SYMS = _gens()

def normalize(cells):
    """Translate so that the lexicographically smallest cell lands at (0,0,s) with s its own sum class."""
    m = min(cells)
    # translation vector must have zero sum; move m to (0, 0, sum(m))
    u, v = -m[0], -m[1]
    w = -(u + v)
    return frozenset((a + u, b + v, c + w) for a, b, c in cells)

def canon(cells):
    best = None
    for f in SYMS:
        n = tuple(sorted(normalize([f(t) for t in cells])))
        if best is None or n < best:
            best = n
    return best

def aspects(cells):
    return {normalize([f(t) for t in cells]) for f in SYMS}

def connected(cells):
    cells = set(cells); start = next(iter(cells)); seen = {start}; st = [start]
    while st:
        u = st.pop()
        for v in nbrs(u):
            if v in cells and v not in seen:
                seen.add(v); st.append(v)
    return len(seen) == len(cells)

def free_polyiamonds(n):
    cur = {canon([(0, 0, 1)])}
    for _ in range(n - 1):
        nxt = set()
        for p in cur:
            s = set(p)
            for t in p:
                for v in nbrs(t):
                    if v not in s:
                        nxt.add(canon(s | {v}))
        cur = nxt
    return cur

# ---- the two pieces, from the definition (Ishino names used on Sicherman's heptiamond page) ----
def strip(n, a=0):
    """n triangles in a row (one horizontal strip a), starting with a down triangle."""
    out = [(a, 0, 1 - a)]
    while len(out) < n:
        x, y, z = out[-1]
        out.append((x, y + 1, z) if x + y + z == 1 else (x, y, z - 1))
    return out

def piece_M():
    """M: a row of five triangles (down, up, down, up, down) with one more triangle on each of the two up
    triangles, on the side away from the row: two 'peaks' on one side, as in Sicherman's labels.png."""
    row = strip(5)
    ups = [t for t in row if sum(t) == 2]
    extra = []
    for u in ups:
        for v in nbrs(u):
            if v not in row and v[0] != u[0]:
                extra.append(v)
    return row + extra

def piece_X():
    """X: the pinwheel. A centre up triangle, its three down neighbours, and on each of those one further
    up triangle, always turning the same way, so the piece has 3-fold rotational symmetry and no mirror."""
    c0 = (0, 1, 1)
    cells = [c0]
    for i in range(3):
        e = [0, 0, 0]; e[i] = 1
        arm = tuple(c0[j] - e[j] for j in range(3))        # down neighbour across coordinate i
        f = [0, 0, 0]; f[(i + 1) % 3] = 1
        cells += [arm, tuple(arm[j] + f[j] for j in range(3))]  # its up neighbour across coordinate i+1
    return cells

def tilings_union(piece, k, limit=None):
    """All connected figures (canonical) that are unions of k non-overlapping copies of piece (any aspect)."""
    asp = [sorted(a) for a in aspects(piece)]
    cur = {canon(piece)}
    for j in range(2, k + 1):
        nxt = set()
        for fig in cur:
            s = set(fig)
            border = {v for t in fig for v in nbrs(t) if v not in s}
            for b in border:
                for a in asp:
                    for anchor in a:
                        # translate aspect so that 'anchor' sits on border cell b (same up/down class)
                        if sum(anchor) != sum(b):
                            continue
                        du, dv, dw = b[0] - anchor[0], b[1] - anchor[1], b[2] - anchor[2]
                        pl = [(x + du, y + dv, z + dw) for x, y, z in a]
                        if any(t in s for t in pl):
                            continue
                        nxt.add(canon(s.union(pl)))
        cur = nxt
        if limit and len(cur) > limit:
            raise RuntimeError("too many figures")
    return cur

if __name__ == "__main__":
    kmax = int(sys.argv[1]) if len(sys.argv) > 1 else 4
    import time
    t0 = time.time()
    hept = free_polyiamonds(7)
    print("free heptiamonds:", len(hept))
    M, X = piece_M(), piece_X()
    print("M", len(set(M)), connected(M), len(aspects(M)), "X", len(set(X)), connected(X), len(aspects(X)))
    print("pieces with 4 aspects:", sum(1 for h in hept if len(aspects(list(h))) == 4))
    for k in range(2, kmax + 1):
        fm = tilings_union(M, k); fx = tilings_union(X, k)
        print(k, len(fm), len(fx), len(fm & fx), round(time.time() - t0, 1), flush=True)
