#!/usr/bin/env python3
"""Independent checker for super edge-magic tree certificates.

Written from the definition only, sharing no code with the solver's checkers
(check_sem.py, verify_cert.py, verify_sem_coverage.py). Deliberately different methods:

  tree test      union-find (no DFS), endpoint range and self-loop checks
  labeling       label set == {1..n}; edge-sum set has n-1 distinct values spanning n-2
  canonical form centre(s) by double BFS on the diameter path (no leaf peeling);
                 rooted canonical level sequence; bicentral trees rooted on the
                 central edge (sorted pair), not min over the two centres
  distinctness   exact byte keys, no hashing
  tree count     A000055(n) computed from Otter's formula, no b-file

A tree is super edge-magic iff there is a bijection f: V -> {1..p} whose q edge sums
are q consecutive integers (Figueroa-Centeno, Ichishima, Muntaner-Batle).

  regeneration   --regen: every free tree on n vertices regenerated by the WROM algorithm
                 (not nauty), each matched by canonical form to exactly one certificate line

Usage: indep_check.py CERT[.xz] [N] [--regen]
Reads n;u-v,...;l0,...,l(n-1)[;extra fields ignored]. Exit 0 iff PASS.
"""
import sys, lzma
from collections import deque


def rooted_counts(N):
    """A000081: r[1..N], rooted unlabeled trees."""
    r = [0] * (N + 1)
    r[1] = 1
    for m in range(1, N):
        s = 0
        for k in range(1, m + 1):
            sd = sum(d * r[d] for d in range(1, k + 1) if k % d == 0)
            s += sd * r[m - k + 1]
        assert s % m == 0
        r[m + 1] = s // m
    return r


def free_trees(n):
    """A000055(n) by Otter: t = r(n) - (sum_{i+j=n} r(i)r(j) - [n even] r(n/2)) / 2."""
    r = rooted_counts(n)
    pairs = sum(r[i] * r[n - i] for i in range(1, n))
    if n % 2 == 0:
        pairs -= r[n // 2]
    assert pairs % 2 == 0
    return r[n] - pairs // 2


def is_tree(n, edges):
    if len(edges) != n - 1:
        return False
    parent = list(range(n))

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for u, v in edges:
        if not (0 <= u < n and 0 <= v < n) or u == v:
            return False
        a, b = find(u), find(v)
        if a == b:
            return False  # cycle (or repeated edge)
        parent[a] = b
    return True  # n-1 edges, acyclic => connected


def sem_ok(n, edges, labels):
    if len(labels) != n or set(labels) != set(range(1, n + 1)):
        return False
    sums = {labels[u] + labels[v] for u, v in edges}
    return len(sums) == n - 1 and max(sums) - min(sums) == n - 2


def bfs(adj, s):
    n = len(adj)
    dist = [-1] * n
    par = [-1] * n
    dist[s] = 0
    q = deque([s])
    while q:
        u = q.popleft()
        for w in adj[u]:
            if dist[w] < 0:
                dist[w] = dist[u] + 1
                par[w] = u
                q.append(w)
    far = max(range(n), key=dist.__getitem__)
    return far, par, dist[far]


def centres(adj):
    a, _, _ = bfs(adj, 0)
    b, par, d = bfs(adj, a)
    path = [b]
    while path[-1] != a:
        path.append(par[path[-1]])
    if d % 2 == 0:
        return [path[d // 2]]
    return [path[d // 2], path[d // 2 + 1]]


def level_seq(adj, v, parent, depth):
    """Canonical level sequence of the subtree at v: children sorted descending."""
    kids = sorted((level_seq(adj, w, v, depth + 1) for w in adj[v] if w != parent), reverse=True)
    out = [depth]
    for k in kids:
        out.extend(k)
    return out


def canon(n, edges):
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    c = centres(adj)
    if len(c) == 1:
        return b"U" + bytes(level_seq(adj, c[0], -1, 0))
    x, y = c
    sx = level_seq(adj, x, y, 0)
    sy = level_seq(adj, y, x, 0)
    lo, hi = sorted([sx, sy])
    return b"B" + bytes(lo) + b"|" + bytes(hi)


def _next_rooted(seq, p=None):
    """WROM: next rooted level sequence (Beyer-Hedetniemi successor), or None."""
    if p is None:
        p = len(seq) - 1
        while seq[p] == 1:
            p -= 1
    if p == 0:
        return None
    q = p - 1
    while seq[q] != seq[p] - 1:
        q -= 1
    out = list(seq)
    for i in range(p, len(out)):
        out[i] = out[i - p + q]
    return out


def _split(seq):
    m = next((i for i in range(2, len(seq)) if seq[i] == 1), len(seq))
    return [x - 1 for x in seq[1:m]], [0] + seq[m:]


def _next_free(cand):
    left, rest = _split(cand)
    lh, rh = max(left), max(rest)
    ok = rh >= lh
    if ok and rh == lh:
        if len(left) > len(rest) or (len(left) == len(rest) and left > rest):
            ok = False
    if ok:
        return cand
    p = len(left)
    new = _next_rooted(cand, p)
    if cand[p] > 2:
        nl, _ = _split(new)
        suf = list(range(1, max(nl) + 2))
        new[-len(suf):] = suf
    return new


def regenerate(n):
    """Every free tree on n >= 4 vertices exactly once, as an edge list.
    Wright, Richmond, Odlyzko and McKay, Constant time generation of free trees,
    SIAM J. Comput. 15 (1986). Independent of nauty gentreeg."""
    seq = list(range(n // 2 + 1)) + list(range(1, (n + 1) // 2))
    while seq is not None:
        seq = _next_free(seq)
        if seq is None:
            return
        last = {}
        edges = []
        for v, lev in enumerate(seq):
            if lev:
                edges.append((last[lev - 1], v))
            last[lev] = v
        yield edges
        seq = _next_rooted(seq)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    regen = "--regen" in sys.argv
    path = args[0]
    want_n = int(args[1]) if len(args) > 1 else None
    opener = lzma.open if path.endswith(".xz") else open
    seen = set()
    lines = malformed = wrong_n = not_tree = bad_label = dup = 0
    first_fail = None
    with opener(path, "rt") as f:
        for raw in f:
            if not raw.strip():
                continue
            lines += 1
            try:
                fs = raw.rstrip("\n").split(";")
                n = int(fs[0])
                edges = [tuple(int(t) for t in e.split("-")) for e in fs[1].split(",")]
                labels = [int(t) for t in fs[2].split(",")]
                assert all(len(e) == 2 for e in edges)
            except Exception:
                malformed += 1
                first_fail = first_fail or ("malformed", lines)
                continue
            if want_n is None:
                want_n = n
            if n != want_n:
                wrong_n += 1
                first_fail = first_fail or ("wrong_n", lines)
                continue
            if not is_tree(n, edges):
                not_tree += 1
                first_fail = first_fail or ("not_tree", lines)
                continue
            if not sem_ok(n, edges, labels):
                bad_label += 1
                first_fail = first_fail or ("bad_label", lines)
            k = canon(n, edges)
            if k in seen:
                dup += 1
                first_fail = first_fail or ("dup", lines)
            seen.add(k)
    expect = free_trees(want_n)
    distinct = len(seen)
    ok = (lines == distinct == expect) and not (malformed or wrong_n or not_tree or bad_label or dup)
    regen_txt = ""
    if regen:
        generated = missing = 0
        for edges in regenerate(want_n):
            generated += 1
            k = canon(want_n, edges)
            if k in seen:
                seen.remove(k)
            else:
                missing += 1  # regenerated tree absent from the certificate (or generated twice)
        extra = len(seen)  # certificate trees the regeneration never produced
        ok = ok and generated == expect and missing == 0 and extra == 0
        regen_txt = f" regenerated={generated} missing={missing} extra={extra}"
    print(f"n={want_n} lines={lines} distinct={distinct} A000055(Otter)={expect} "
          f"malformed={malformed} wrong_n={wrong_n} not_tree={not_tree} bad_label={bad_label} dup={dup}"
          + regen_txt
          + (f" first_fail={first_fail}" if first_fail else "")
          + f" -> {'PASS' if ok else 'FAIL'}")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
