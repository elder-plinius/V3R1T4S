#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>

static uint8_t gf9_add[9][9], gf9_sub[9][9], gf9_mul[9][9], gf9_inv[9], gf9_conj[9];

static void init_gf9(void) {
    for (int x = 0; x < 9; x++) {
        int ax = x % 3, bx = x / 3;
        gf9_conj[x] = ax + 3 * ((2 * bx) % 3);
        for (int y = 0; y < 9; y++) {
            int ay = y % 3, by = y / 3;
            gf9_add[x][y] = ((ax + ay) % 3) + 3 * ((bx + by) % 3);
            gf9_sub[x][y] = ((ax - ay + 3) % 3) + 3 * ((bx - by + 3) % 3);
            int re = (ax * ay + 2 * bx * by) % 3;
            int im = (ax * by + bx * ay) % 3;
            gf9_mul[x][y] = re + 3 * im;
        }
    }
    for (int x = 1; x < 9; x++)
        for (int y = 1; y < 9; y++)
            if (gf9_mul[x][y] == 1) gf9_inv[x] = y;
}

static int rank_gf9(uint8_t A[8][8], int m) {
    uint8_t M[8][8];
    memcpy(M, A, sizeof(M));
    int r = 0;
    for (int c = 0; c < m && r < m; c++) {
        int p = -1;
        for (int i = r; i < m; i++) if (M[i][c]) { p = i; break; }
        if (p < 0) continue;
        for (int j = 0; j < m; j++) { uint8_t t = M[r][j]; M[r][j] = M[p][j]; M[p][j] = t; }
        uint8_t inv = gf9_inv[M[r][c]];
        for (int j = 0; j < m; j++) M[r][j] = gf9_mul[M[r][j]][inv];
        for (int i = 0; i < m; i++) {
            if (i != r && M[i][c]) {
                uint8_t f = M[i][c];
                for (int j = 0; j < m; j++)
                    M[i][j] = gf9_sub[M[i][j]][gf9_mul[f][M[r][j]]];
            }
        }
        r++;
    }
    return r;
}

static int min_weight_14_6(uint8_t H[6][14], int cutoff) {
    for (int i = 0; i < 6; i++) {
        for (int i2 = i + 1; i2 < 6; i2++) {
            for (int a = 1; a < 9; a++) {
                int w = 0;
                for (int j = 0; j < 14; j++)
                    if (gf9_add[H[i][j]][gf9_mul[a][H[i2][j]]]) w++;
                if (w < cutoff) return w;
            }
        }
    }
    int c[6] = {0};
    int min_w = 14;
    while (1) {
        int pos = 5;
        while (pos >= 0 && c[pos] == 8) { c[pos] = 0; pos--; }
        if (pos < 0) break;
        c[pos]++;
        int fnz = 0;
        for (int i = 0; i < 6; i++) if (c[i]) { fnz = c[i]; break; }
        if (fnz != 1) continue;
        int w = 0;
        for (int j = 0; j < 14; j++) {
            uint8_t v = 0;
            for (int i = 0; i < 6; i++) if (c[i]) v = gf9_add[v][gf9_mul[c[i]][H[i][j]]];
            if (v) w++;
        }
        if (w < cutoff) return w;
        if (w < min_w) min_w = w;
    }
    return min_w;
}

int main(void) {
    init_gf9();
    /* g1(x) = (x - 1)(x^3 + 2x + 2) = x^4 + 2x^3 + 2x^2 + 1 (degree 4, generates C1 of dim 3)
     * g2(x) = (x - 1)(x^3 + x^2 + 2) = x^4 + 2x^2 + 2x + 1 (degree 4, generates C2 of dim 3)
     * Any vector in C1 has the form a(x) * g1(x) mod (x^7 - 1).
     * Notice EVERY code spanned by 3 cyclic shifts of (u1, v1) in C1 x C1 and 3 cyclic shifts of (u2, v2) in C2 x C2
     * has C1 x C1 automatically Hermitian self-orthogonal (so rank(H H^dagger) <= 3, ell >= 3)!
     * Even simpler: take ANY 2-quasi-cyclic code of dim 6 generated by:
     *   rows 0..2: cyclic shifts of (g1(x), f1(x)*g1(x) + h1(x)*g2(x))
     *   rows 3..5: cyclic shifts of (0,     f2(x)*g2(x)) or general 2-generator QC!
     * Or first test ALL 1-generator 2-QC codes of dim 6: rows 0..5 = shifts 0..5 of ((x-1)*a(x), (x-1)*b(x))!
     */
    uint8_t g1[7] = {1, 0, 2, 2, 1, 0, 0}; /* 1 + 2x^2 + 2x^3 + x^4 */
    uint8_t g2[7] = {1, 2, 2, 0, 1, 0, 0}; /* 1 + 2x + 2x^2 + x^4 */

    uint64_t rng = 0x5555555512345678ULL;
    int best_mw = 0, hits = 0;

    for (long t = 0; t < 2000000L; t++) {
        /* Build row 0 in C1 x (C1 + C2) so rows 0..2 are cyclic shifts of row 0,
         * and row 3 in C2 x (C1 + C2) so rows 3..5 are cyclic shifts of row 3!
         * Wait: if row 0 is in C1 x C1, then rows 0..2 are automatically self-orthogonal AND orthogonal to C1 x C1!
         *Wait: in GF(9)[x]/(x^7-1), the Hermitian inner product of two polynomials u(x), v(x) is the constant term of u(x) * conj(v(x^-1)).
         * Since g1(x) * conj(g1(x^-1)) is divisible by p2(x) * p2(x^-1) = p2(x) * p1(x),
         * ANY two vectors in C1 = <g1(x)> are AUTOMATICALLY HERMITIAN ORTHOGONAL!
         * YES!! For ANY u(x), v(x) in C1 = <(x-1)p2(x)>, u * v^dagger == 0!
         * So ANY 3-dimensional code in C1 x C1 is 100% HERMITIAN SELF-ORTHOGONAL! */
        uint8_t c1_a[3], c1_b[3], c2_a[3], c2_b[3];
        for (int i = 0; i < 3; i++) {
            rng ^= rng << 13; rng ^= rng >> 7; rng ^= rng << 17; c1_a[i] = rng % 9;
            rng ^= rng << 13; rng ^= rng >> 7; rng ^= rng << 17; c1_b[i] = rng % 9;
            rng ^= rng << 13; rng ^= rng >> 7; rng ^= rng << 17; c2_a[i] = rng % 9;
            rng ^= rng << 13; rng ^= rng >> 7; rng ^= rng << 17; c2_b[i] = rng % 9;
        }
        uint8_t r1_L[7] = {0}, r1_R[7] = {0}, r2_L[7] = {0}, r2_R[7] = {0};
        for (int i = 0; i < 3; i++) {
            for (int j = 0; j < 7; j++) {
                int idx = (j - i + 7) % 7;
                r1_L[j] = gf9_add[r1_L[j]][gf9_mul[c1_a[i]][g1[idx]]];
                r1_R[j] = gf9_add[r1_R[j]][gf9_mul[c1_b[i]][g1[idx]]];
                r2_L[j] = gf9_add[r2_L[j]][gf9_mul[c2_a[i]][g2[idx]]];
                r2_R[j] = gf9_add[r2_R[j]][gf9_mul[c2_b[i]][g2[idx]]];
            }
        }
        /* Combine r1 + r2 as generator of a 6D 2-QC code: shifts 0..5 of (r1_L + r2_L | r1_R + r2_R) */
        uint8_t H[6][14];
        for (int s = 0; s < 6; s++) {
            for (int j = 0; j < 7; j++) {
                int idx = (j - s + 7) % 7;
                H[s][j] = gf9_add[r1_L[idx]][r2_L[idx]];
                H[s][7 + j] = gf9_add[r1_R[idx]][r2_R[idx]];
            }
        }
        /* Check if rank(H H^dagger) <= 3 */
        uint8_t G[8][8] = {{0}};
        for (int i = 0; i < 6; i++)
            for (int j = 0; j < 6; j++)
                for (int c = 0; c < 14; c++)
                    G[i][j] = gf9_add[G[i][j]][gf9_mul[H[i][c]][gf9_conj[H[j][c]]]];
        int rk = rank_gf9(G, 6);
        if (rk > 3) continue;
        hits++;
        int mw = min_weight_14_6(H, best_mw > 7 ? best_mw : 7);
        if (mw > best_mw) {
            best_mw = mw;
            printf("Hit #%d: rk=%d (ell=%d), mw=%d\n", hits, rk, 6 - rk, mw);
            if (mw >= 8) {
                printf("FOUND 2-QC PURE [14, 6, %d]_9 WITH HULL ELL=%d!\n", mw, 6 - rk);
                for (int i = 0; i < 6; i++) {
                    printf("[");
                    for (int j = 0; j < 14; j++) printf("%d%s", H[i][j], j == 13 ? "" : ", ");
                    printf("],\n");
                }
                return 0;
            }
        }
    }
    printf("Done: hits=%d, best_mw=%d\n", hits, best_mw);
    return 0;
}
