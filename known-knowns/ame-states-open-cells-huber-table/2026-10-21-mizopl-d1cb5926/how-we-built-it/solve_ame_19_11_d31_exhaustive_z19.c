/*
 * Theorem D31 Exhaustive Solver for Symmetric 19-Circulants over F_11 (AME(19, 11) = [[19, 0, 10]]_11):
 *   1. Uses the exact Z_2-folded (5x5) + (4x5) block decomposition of all 126 reflection-self-conjugate
 *      orbits (tau(S) = S) of Z_19:
 *        rank(A_{S, S^c}) == 9  <==>  det((C_+)_{{0} U I, J}) != 0  AND  rank((C_-)_{I, J}) == 4.
 *   2. Quotients the 11^9 - 1 = 2,357,947,690 non-zero symmetric 19-circulants by F_11^* scaling (x10)
 *      and the multiplicative automorphism group (Z/19Z)^* / {+-1} = <2 mod 19> ~= Z_9 (x9),
 *      yielding 26,199,429 canonical necklaces (plus we also track the best min-bad across all 126 + 2368 orbits).
 */

#define P 11
static uint8_t inv11[11];
static int dist_tab[19][19];
static int plus_d1[10][9], plus_d2[10][9];

/* 126 subsets I of {1..9} of size 4, and their complements J of size 5 */
static int sub_I[126][4];
static int sub_J[126][5];

/* All 2,368 non-self-conjugate dihedral orbits of 9-subsets of Z_19 */
static uint8_t gen_S[2368][9];
static uint8_t gen_Sc[2368][10];
static int n_gen_orbs = 0;

/* 9-cycle of (Z/19Z)^* / {+-1} generated by x -> 2x mod 19 on {1..9}:
 * 1 -> 2 -> 4 -> 8 -> 3 -> 6 -> 7 -> 5 -> 9 -> 1
 */
static const int cyc9[9] = {1, 2, 4, 8, 3, 6, 7, 5, 9};
static int cyc9_shift[9][9]; /* cyc9_shift[s][idx] = image of coordinate idx (0..8) under shift s */

static void init_tables(void) {
    inv11[0] = 0;
    for (int a = 1; a < 11; a++)
        for (int b = 1; b < 11; b++)
            if ((a * b) % 11 == 1) inv11[a] = (uint8_t)b;

    for (int i = 0; i < 19; i++)
        for (int j = 0; j < 19; j++) {
            int d = abs(i - j);
            dist_tab[i][j] = (d <= 9) ? d : (19 - d);
        }

    for (int v = 1; v <= 9; v++) {
        plus_d1[0][v - 1] = v;
        plus_d2[0][v - 1] = 0;
        for (int u = 1; u <= 9; u++) {
            plus_d1[u][v - 1] = dist_tab[u][v];
            plus_d2[u][v - 1] = dist_tab[u][19 - v];
        }
    }

    int idx = 0;
    for (int m = 0; m < 512; m++) {
        if (__builtin_popcount(m) != 4) continue;
        int ii = 0, ji = 0;
        for (int u = 1; u <= 9; u++) {
            if ((m >> (u - 1)) & 1) sub_I[idx][ii++] = u;
            else                    sub_J[idx][ji++] = u - 1;
        }
        idx++;
    }

    /* Map 0..8 -> position in cyc9 */
    int pos_in_cyc[10];
    for (int k = 0; k < 9; k++) pos_in_cyc[cyc9[k]] = k;
    for (int s = 0; s < 9; s++) {
        for (int u = 1; u <= 9; u++) {
            int nu = cyc9[(pos_in_cyc[u] + s) % 9];
            cyc9_shift[s][u - 1] = nu - 1;
        }
    }

    /* Enumerate all 9-subsets of Z_19 modulo D_19 = Z_19 x {+-1} */
    int n_self = 0;
    for (uint32_t m = 0; m < (1u << 19); m++) {
        if (__builtin_popcount(m) != 9) continue;
        /* Canonicalize under D_19 */
        uint32_t best = m;
        int is_self = 0;
        for (int s = 0; s < 19; s++) {
            uint32_t ms = 0, mr = 0;
            for (int i = 0; i < 19; i++) {
                if ((m >> i) & 1) {
                    ms |= (1u << ((i + s) % 19));
                    mr |= (1u << ((19 - i + s) % 19));
                }
            }
            if (ms < best) best = ms;
            if (mr < best) best = mr;
            if (mr == m) is_self = 1;
        }
        if (best != m) continue;
        if (is_self) {
            n_self++;
        } else {
            int si = 0, sci = 0;
            for (int i = 0; i < 19; i++) {
                if ((m >> i) & 1) gen_S[n_gen_orbs][si++] = (uint8_t)i;
                else              gen_Sc[n_gen_orbs][sci++] = (uint8_t)i;
            }
            n_gen_orbs++;
        }
    }
    printf("Initialized D_19 orbits: %d self-conjugate + %d generic = %d total dihedral orbits\n",
           n_self, n_gen_orbs, n_self + n_gen_orbs);
}

static inline int det5_mod11(uint8_t M[5][5]) {
    for (int col = 0; col < 5; col++) {
        int piv = -1;
        for (int row = col; row < 5; row++)
            if (M[row][col]) { piv = row; break; }
        if (piv < 0) return 0;
        if (piv != col) {
            for (int c = col; c < 5; c++) {
                uint8_t t = M[col][c]; M[col][c] = M[piv][c]; M[piv][c] = t;
            }
        }
        uint8_t iv = inv11[M[col][col]];
        for (int row = col + 1; row < 5; row++) {
            if (!M[row][col]) continue;
            uint8_t f = (M[row][col] * iv) % 11;
            for (int c = col + 1; c < 5; c++) {
                M[row][c] = (M[row][c] + 110 - f * M[col][c]) % 11;
            }
        }
    }
    return 1;
}

static inline int rank4x5_mod11(uint8_t M[4][5]) {
    int r = 0;
    for (int col = 0; col < 5 && r < 4; col++) {
        int piv = -1;
        for (int row = r; row < 4; row++)
            if (M[row][col]) { piv = row; break; }
        if (piv < 0) continue;
        if (piv != r) {
            for (int c = col; c < 5; c++) {
                uint8_t t = M[r][c]; M[r][c] = M[piv][c]; M[piv][c] = t;
            }
        }
        uint8_t iv = inv11[M[r][col]];
        for (int row = r + 1; row < 4; row++) {
            if (!M[row][col]) continue;
            uint8_t f = (M[row][col] * iv) % 11;
            for (int c = col + 1; c < 5; c++) {
                M[row][c] = (M[row][c] + 110 - f * M[r][c]) % 11;
            }
        }
        r++;
    }
    return r == 4;
}

static inline int rank9x10_mod11(const uint8_t a[10], int orb_idx) {
    uint8_t M[9][10];
    const uint8_t *S = gen_S[orb_idx];
    const uint8_t *Sc = gen_Sc[orb_idx];
    for (int i = 0; i < 9; i++) {
        int si = S[i];
        for (int j = 0; j < 10; j++)
            M[i][j] = a[dist_tab[si][Sc[j]]];
    }
    int r = 0;
    for (int col = 0; col < 10 && r < 9; col++) {
        int piv = -1;
        for (int row = r; row < 9; row++)
            if (M[row][col]) { piv = row; break; }
        if (piv < 0) continue;
        if (piv != r) {
            for (int c = col; c < 10; c++) {
                uint8_t t = M[r][c]; M[r][c] = M[piv][c]; M[piv][c] = t;
            }
        }
        uint8_t iv = inv11[M[r][col]];
        for (int row = r + 1; row < 9; row++) {
            if (!M[row][col]) continue;
            uint8_t f = (M[row][col] * iv) % 11;
            for (int c = col + 1; c < 10; c++) {
                M[row][c] = (M[row][c] + 110 - f * M[r][c]) % 11;
            }
        }
        r++;
    }
    return r == 9;
}

static int global_min_self = 126;
static int global_min_tot = 2494;
static uint64_t total_necklaces = 0;
static uint64_t zero_self_count = 0;
static pthread_mutex_t lock = PTHREAD_MUTEX_INITIALIZER;

/* Check if a[1..9] is canonical under F_11^* scaling and Z_9 automorphism shift */
static inline int is_canonical(const uint8_t a[10]) {
    uint64_t base_code = 0;
    for (int i = 1; i <= 9; i++) base_code = base_code * 11 + a[i];

    for (int s = 1; s < 9; s++) {
        uint8_t first_v = a[cyc9_shift[s][0] + 1];
        if (first_v == 0) continue; /* shifted vector has a'[1] == 0, outside the a[1]==1 slice */
        uint8_t scale = inv11[first_v];
        uint64_t code = 0;
        for (int i = 0; i < 9; i++) {
            uint8_t v = (a[cyc9_shift[s][i] + 1] * scale) % 11;
            code = code * 11 + v;
        }
        if (code < base_code) return 0;
    }
    return 1;
}

#define N_THREADS 8

static void *worker(void *arg) {
    int tid = (int)(uintptr_t)arg;
    uint64_t local_neck = 0, local_zself = 0;
    uint8_t a[10];
    a[0] = 0;

    /* Partition top-level index (a[1]=1, a[2] in 0..10, a[3] in 0..10 -> 121 buckets) plus a[1]=0 cases */
    for (int bucket = tid; bucket < 121; bucket += N_THREADS) {
        a[1] = 1;
        a[2] = (uint8_t)(bucket / 11);
        a[3] = (uint8_t)(bucket % 11);
        for (int a4 = 0; a4 < 11; a4++) {
            a[4] = (uint8_t)a4;
            for (int a5 = 0; a5 < 11; a5++) {
                a[5] = (uint8_t)a5;
                for (int a6 = 0; a6 < 11; a6++) {
                    a[6] = (uint8_t)a6;
                    for (int a7 = 0; a7 < 11; a7++) {
                        a[7] = (uint8_t)a7;
                        for (int a8 = 0; a8 < 11; a8++) {
                            a[8] = (uint8_t)a8;
                            for (int a9 = 0; a9 < 11; a9++) {
                                a[9] = (uint8_t)a9;
                                if (!is_canonical(a)) continue;
                                local_neck++;

                                /* Build C_+ (10x9) and C_- (9x9) */
                                uint8_t Cp[10][9], Cm[10][9];
                                for (int v = 0; v < 9; v++) {
                                    Cp[0][v] = a[v + 1];
                                    for (int u = 1; u <= 9; u++) {
                                        uint8_t x = a[plus_d1[u][v]];
                                        uint8_t y = a[plus_d2[u][v]];
                                        Cp[u][v] = (x + y) % 11;
                                        Cm[u][v] = (x + 11 - y) % 11;
                                    }
                                }

                                int bad_self = 0;
                                int cap_self = (global_min_self < 2) ? global_min_self : 1;
                                for (int k = 0; k < 126; k++) {
                                    uint8_t M5[5][5];
                                    const int *I = sub_I[k];
                                    const int *J = sub_J[k];
                                    for (int c = 0; c < 5; c++) M5[0][c] = Cp[0][J[c]];
                                    for (int r = 0; r < 4; r++)
                                        for (int c = 0; c < 5; c++)
                                            M5[r + 1][c] = Cp[I[r]][J[c]];
                                    if (!det5_mod11(M5)) {
                                        if (++bad_self > cap_self) break;
                                        continue;
                                    }
                                    uint8_t M4[4][5];
                                    for (int r = 0; r < 4; r++)
                                        for (int c = 0; c < 5; c++)
                                            M4[r][c] = Cm[I[r]][J[c]];
                                    if (!rank4x5_mod11(M4)) {
                                        if (++bad_self > cap_self) break;
                                    }
                                }
                                if (bad_self > cap_self) continue;

                                if (bad_self == 0) local_zself++;

                                /* Evaluate generic orbits with early exit at global_min_tot */
                                int bad_gen = 0;
                                int max_gen = global_min_tot - bad_self;
                                for (int g = 0; g < n_gen_orbs; g++) {
                                    if (!rank9x10_mod11(a, g)) {
                                        if (++bad_gen > max_gen) break;
                                    }
                                }
                                int tot = bad_self + bad_gen;
                                if (bad_self < global_min_self || tot < global_min_tot) {
                                    pthread_mutex_lock(&lock);
                                    if (bad_self < global_min_self) global_min_self = bad_self;
                                    if (tot < global_min_tot) {
                                        global_min_tot = tot;
                                        printf("[D31-Z19 T%d] self=%d/126 | gen=%d/2368 | TOTAL=%d/2494 (%.4f%%) a=[%d,%d,%d,%d,%d,%d,%d,%d,%d]\n",
                                               tid, bad_self, bad_gen, tot, 100.0 * (2494 - tot) / 2494.0,
                                               a[1],a[2],a[3],a[4],a[5],a[6],a[7],a[8],a[9]);
                                        fflush(stdout);
                                    }
                                    pthread_mutex_unlock(&lock);
                                }
                            }
                        }
                    }
                }
            }
        }
    }

    pthread_mutex_lock(&lock);
    total_necklaces += local_neck;
    zero_self_count += local_zself;
    pthread_mutex_unlock(&lock);
    return NULL;
}

int main(void) {
    init_tables();
    struct timespec t0, t1;
    clock_gettime(CLOCK_MONOTONIC, &t0);

    pthread_t th[N_THREADS];
    for (int i = 0; i < N_THREADS; i++) pthread_create(&th[i], NULL, worker, (void*)(uintptr_t)i);
    for (int i = 0; i < N_THREADS; i++) pthread_join(th[i], NULL);

    clock_gettime(CLOCK_MONOTONIC, &t1);
    double dt = (t1.tv_sec - t0.tv_sec) + 1e-9 * (t1.tv_nsec - t0.tv_nsec);
    printf("\n=== EXHAUSTIVE Z_19 SWEEP OVER F_11 COMPLETE in %.2f s ===\n", dt);
    printf("Canonical necklaces evaluated: %llu (representing all 11^9 - 1 = 2,357,947,690 symmetric 19-circulants)\n",
           (unsigned long long)total_necklaces);
    printf("Necklaces with 0 / 126 bad self-conjugate orbits: %llu\n", (unsigned long long)zero_self_count);
    printf("Global minimum bad dihedral orbits: %d / 2494 (min_self = %d / 126)\n", global_min_tot, global_min_self);
    return 0;
}
