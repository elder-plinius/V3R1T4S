"""Larger conditioning windows for the van den Berg-Ermakov (1996) growth-process comparison, exact arithmetic.

Setting (paper, Sections 3-4): site percolation on L at parameter p, written as percolation on S with four defect
types eps(v) = (upper, lower); eps-adjacency of neighbours v, w (min = smaller coordinate sum) is upper-upper,
lower-lower or upper(min)-lower(max). The growth process reveals eta on parent-child edges only, so everything
known before b2 is processed is a set of constraints on the edges of the exploration tree. The children of b2 are
fresh sites, so their joint law given the past is sum_beta w(beta) nu_beta, with w the posterior of eps(b2): belief
propagation on a tree. The domination condition sum_beta w(beta) (nu_beta(A) - pi_{1-p}(A)) >= 0 (w unnormalized)
is multilinear in the messages entering c, so the worst case over any set of messages is attained at the extreme
rays of its conic hull.

Message sets (3-vectors over the open states of the receiving vertex, pruned to extreme rays):
  D_k[o]: from a child subtree whose root b has orientation o (b is the max or min neighbour of its parent):
          absent slot (all ones), eta = 0 leaf, or eta = 1 with b's own child slots from D_{k-1};
          D_0 replaces b's subtree by an adversarial point mass on eps(b) (as the paper does).
  U_k[o]: from the parent side of a vertex x of orientation o: the parent y, y's other child slots from D_{k-1},
          y's parent side from U_{k-1} (or y is the root, with four child slots); U_0 is a point mass on eps(y).
Child slots of a vertex whose parent is its min neighbour: (max, max, min); parent is max: (max, min, min);
root: (max, max, min, min). Depth k = 0 is the paper's window; k = 1 adds the parent of d, the brothers of c and
the children of c's other children (Remark (iv)).

Every superset of the real pasts is checked, so a check that passes at a rational p proves p_c(S) >= 1 - p.

usage: python window.py <k_max> [p_lo p_hi]   (bisection for the best bound at each depth 0..k_max)
"""
import sys
from fractions import Fraction as F
from itertools import product

ALL = [(0, 0), (1, 0), (0, 1), (1, 1)]  # (upper, lower)
OPEN = [(1, 0), (0, 1), (1, 1)]


def adj(smin, smax):
    return bool((smin[0] and smax[0]) or (smin[1] and smax[1]) or (smin[0] and smax[1]))


def A(par, child, o):
    """eta of the edge between a parent in state par and a child in state child, child orientation o."""
    return adj(par, child) if o == "max" else adj(child, par)


def SLOTS(side):
    return {"min": ["max", "max", "min"], "max": ["max", "min", "min"], "root": ["max", "max", "min", "min"]}[side]


def side_of(o):
    """A vertex with orientation o (relative to its parent) has its parent on this side."""
    return "min" if o == "max" else "max"


def hull(vecs):
    """Extreme rays of the cone generated by nonnegative 3-vectors (exact)."""
    pts = {}
    for v in vecs:
        s = sum(v)
        if s == 0:
            continue
        key = (v[0] / s, v[1] / s)
        pts[key] = v
    P = sorted(pts)
    if len(P) <= 2:
        return [pts[k] for k in P]

    def cross(o, a, b):
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])

    lower, upper = [], []
    for pt in P:
        while len(lower) >= 2 and cross(lower[-2], lower[-1], pt) <= 0:
            lower.pop()
        lower.append(pt)
    for pt in reversed(P):
        while len(upper) >= 2 and cross(upper[-2], upper[-1], pt) <= 0:
            upper.pop()
        upper.append(pt)
    return [pts[k] for k in lower[:-1] + upper[:-1]]


GRID = 2 ** 40


def round_out(gens):
    """Replace each generator (normalized to sum 1, all entries >= 0) by a small triangle with grid coordinates
    that contains it: floor all three coordinates to the grid, then give the remainder r to each coordinate in
    turn. The three vertices are >= 0, sum to 1, and their convex hull contains the point, so the new cone
    contains the old one (a superset is sound) while the numbers stay small."""
    out = []
    for v in gens:
        s = sum(v)
        assert s > 0 and min(v) >= 0
        u = [c / s for c in v]
        f = [F(int(c * GRID), GRID) for c in u]  # floor (c >= 0)
        r = 1 - sum(f)
        if r == 0:
            out.append(tuple(f))
            continue
        for i in range(3):
            t = list(f)
            t[i] += r
            out.append(tuple(t))
    return hull(out)


class Model:
    def __init__(self, p):
        self.p = p
        q = 1 - p
        self.pi = {s: (p if s[0] else q) * (p if s[1] else q) for s in ALL}
        self.ones = (F(1), F(1), F(1))

    def leaf0(self, o):
        return tuple(sum(self.pi[b] * (0 if A(g, b, o) else 1) for b in ALL) for g in OPEN)

    def D0(self, o):
        gens = [self.leaf0(o), self.ones] + [tuple(F(int(A(g, b, o))) for g in OPEN) for b in OPEN]
        return hull(gens)

    def U0(self, o):
        # message into x (state gamma) from parent y in point-mass state delta: A(delta, gamma, o)
        return hull([tuple(F(int(A(d, g, o))) for g in OPEN) for d in OPEN])

    def Dnext(self, Dprev):
        out = {}
        for o in ("max", "min"):
            gens = [self.leaf0(o), self.ones]
            slots = SLOTS(side_of(o))
            for ms in product(*[Dprev[s] for s in slots]):
                f = [self.pi[b] * ms[0][i] * ms[1][i] * ms[2][i] for i, b in enumerate(OPEN)]
                gens.append(tuple(sum(f[i] for i, b in enumerate(OPEN) if A(g, b, o)) for g in OPEN))
            out[o] = round_out(hull(gens))
        return out

    def Unext(self, Uprev, Dprev):
        out = {}
        for o in ("max", "min"):  # orientation of x relative to its parent y
            gens = []
            for yside in ("min", "max", "root"):
                slots = list(SLOTS(yside))
                if o not in slots:
                    continue
                slots.remove(o)
                pars = [self.ones] if yside == "root" else Uprev["max" if yside == "min" else "min"]
                for mp in pars:
                    for ms in product(*[Dprev[s] for s in slots]):
                        f = []
                        for i, d in enumerate(OPEN):
                            t = self.pi[d] * mp[i]
                            for m in ms:
                                t *= m[i]
                            f.append(t)
                        gens.append(tuple(sum(f[i] for i, d in enumerate(OPEN) if A(d, g, o)) for g in OPEN))
            out[o] = round_out(hull(gens))
        return out

    def check(self, U, D):
        """Worst margin of the domination condition over all window cases (normalized by sum of w)."""
        p = self.p
        lam = 1 - p
        ups = UPSETS
        worst = None
        for ob in ("max", "min"):  # orientation of b2 relative to c
            kids = SLOTS(side_of(ob))
            # child adjacency probabilities given eps(b2) = beta
            P = {b: [sum(self.pi[a] for a in ALL if A(b, a, ok)) for ok in kids] for b in OPEN}
            nu = {}
            for b in OPEN:
                for x in PTS:
                    t = F(1)
                    for xi, pp in zip(x, P[b]):
                        t *= pp if xi else 1 - pp
                    nu[b, x] = t
            coef = {}
            for ui, Aset in enumerate(ups):
                piA = sum((lam if x[0] else 1 - lam) * (lam if x[1] else 1 - lam) * (lam if x[2] else 1 - lam)
                          for x in Aset)
                for b in OPEN:
                    coef[ui, b] = sum(nu[b, x] for x in Aset) - piA
            for cside in ("min", "max", "root"):
                slots = list(SLOTS(cside))
                slots.remove(ob)
                pars = [self.ones] if cside == "root" else U["max" if cside == "min" else "min"]
                for mp in pars:
                    for ms in product(*[D[s] for s in slots]):
                        mu = []
                        for i, g in enumerate(OPEN):
                            t = self.pi[g] * mp[i]
                            for m in ms:
                                t *= m[i]
                            mu.append(t)
                        w = {b: self.pi[b] * sum(mu[i] for i, g in enumerate(OPEN) if A(g, b, ob)) for b in OPEN}
                        sw = sum(w.values())
                        for ui in range(len(ups)):
                            m = sum(w[b] * coef[ui, b] for b in OPEN) / sw
                            if worst is None or m < worst[0]:
                                worst = (m, ob, cside)
        return worst


PTS = list(product((0, 1), repeat=3))
UPSETS = []
for mask in range(1, 2 ** 8 - 1):
    S = {PTS[i] for i in range(8) if mask >> i & 1}
    if all(y in S for x in S for y in PTS if all(b >= a for a, b in zip(x, y))):
        UPSETS.append(frozenset(S))


def levels(p, kmax):
    M = Model(p)
    D = {o: M.D0(o) for o in ("max", "min")}
    U = {o: M.U0(o) for o in ("max", "min")}
    yield 0, M, U, D
    for k in range(1, kmax + 1):
        U, D = M.Unext(U, D), M.Dnext(D)
        yield k, M, U, D


def margin_at(p, k):
    for kk, M, U, D in levels(p, k):
        if kk == k:
            return M.check(U, D), {o: len(U[o]) for o in U}, {o: len(D[o]) for o in D}


def best_bound(k, lo, hi, steps=26):
    """Bisection on p with denominators 10^9: returns the smallest p (to 1e-9) at which the check passes."""
    N = 10 ** 9
    a, b = int(lo * N), int(hi * N)
    assert margin_at(F(b, N), k)[0][0] > 0, "check fails at the upper end"
    if margin_at(F(a, N), k)[0][0] > 0:
        return F(a, N)
    while b - a > 1:
        m = (a + b) // 2
        if margin_at(F(m, N), k)[0][0] > 0:
            b = m
        else:
            a = m
    return F(b, N)


def main():
    kmax = int(sys.argv[1]) if len(sys.argv) > 1 else 2
    lo = F(sys.argv[2]) if len(sys.argv) > 2 else F(40, 100)
    hi = F(sys.argv[3]) if len(sys.argv) > 3 else F(4442, 10000)
    print("increasing events:", len(UPSETS))
    w0, nu_, nd_ = margin_at(F(444, 1000), 0)
    print("depth 0 at p = 0.444: worst margin %.6e (case b2 %s child, c parent side %s); |U| %s |D| %s"
          % (float(w0[0]), w0[1], w0[2], nu_, nd_))
    for k in range(0, kmax + 1):
        pk = best_bound(k, lo, hi)
        wk, nu_, nd_ = margin_at(pk, k)
        print("depth %d: check passes for p >= %s, so p_c(S) >= 1 - p = %.9f  (|U| %s |D| %s, margin there %.2e)"
              % (k, pk, float(1 - pk), nu_, nd_, float(wk[0])), flush=True)


if __name__ == "__main__":
    main()
