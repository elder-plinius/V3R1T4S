#!/usr/bin/env python3
"""Generate closed-form matrix elements for three-body exponential bases with L = 1 or 2 (natural parity).

Particles 1, 2 (masses M1, M2) and 3 (mass M3).  x = r1 - r3, y = r2 - r3, X = |x|, Y = |y|, R = |x - y|.
Basis function: P_t(x, y) * exp(-a X - b Y - c R), P_t a Cartesian tensor of rank L (types below).
Bilinear forms (no complex conjugation), summed over all Cartesian components, with the common factor 8 pi^2 dropped:
  S = <bra|ket>,   H = T + V,
  T = 1/2 sum [ w1 grad_x.grad_x + w2 grad_y.grad_y + w3 (grad_x.grad_y + grad_y.grad_x) ],
      w1 = 1/M1 + 1/M3, w2 = 1/M2 + 1/M3, w3 = 1/M3   (centre of mass removed, gradient form)
  V = q13/X + q23/Y + q12/R.
Radial integrals use perimetric coordinates X = p + q, Y = p + r, R = q + r (Jacobian 2):
  int p^i q^j r^k exp(-(A+B)p - (A+C)q - (B+C)r) = i! j! k! u^(i+1) wq^(j+1) v^(k+1),
  u = 1/(A+B), wq = 1/(A+C), v = 1/(B+C), A = a + d, B = b + e, C = c + g.
Output: C++ header elems_L<L>.h with template functions; all results carry the same integer scale SCALE_L.
"""
import sys, sympy as sp
L = int(sys.argv[1])
X, Y, R = sp.symbols('X Y R', positive=True)
a, b, c, d, e, g = sp.symbols('a b c d e g')
w1, w2, w3, q13, q23, q12 = sp.symbols('w1 w2 w3 q13 q23 q12')
xs = sp.symbols('x1:4'); ys = sp.symbols('y1:4')
p, q, r = sp.symbols('p q r', positive=True)
u, wq, v = sp.symbols('u wq v')
ct, st = sp.symbols('ct st')
rs = [xs[i] - ys[i] for i in range(3)]
dot = lambda s, t: sum(s[i] * t[i] for i in range(3))
kd = lambda i, j: 1 if i == j else 0
if L == 1:
    types = {'x': [xs[k] for k in range(3)], 'y': [ys[k] for k in range(3)], 'r': [rs[k] for k in range(3)]}
elif L == 2:
    def stf(s, t):
        return [sp.Rational(1, 2) * (s[i] * t[j] + s[j] * t[i]) - sp.Rational(1, 3) * kd(i, j) * dot(s, t)
                for i in range(3) for j in range(3)]
    types = {'xx': stf(xs, xs), 'xy': stf(xs, ys), 'yy': stf(ys, ys), 'rr': stf(rs, rs)}
else:
    raise SystemExit('L must be 1 or 2')
names = list(types)

def grads(P, al, be, ga):
    """(grad_x, grad_y) of P*f divided by f, f = exp(-al X - be Y - ga R); lists over j."""
    gx = [sp.diff(P, xs[j]) + P * (-al * xs[j] / X - ga * (xs[j] - ys[j]) / R) for j in range(3)]
    gy = [sp.diff(P, ys[j]) + P * (-be * ys[j] / Y + ga * (xs[j] - ys[j]) / R) for j in range(3)]
    return gx, gy

orient = {xs[0]: X, xs[1]: 0, xs[2]: 0, ys[0]: Y * ct, ys[1]: Y * st, ys[2]: 0}

def reduce_scalar(expr):
    ex = sp.expand(expr.subs(orient))
    ex = sp.Poly(ex, st)
    out = 0
    for (n,), cf in ex.terms():
        assert n % 2 == 0, 'odd power of sin'
        out += cf * (1 - ct**2) ** (n // 2)
    out = sp.expand(out).subs(ct, (X**2 + Y**2 - R**2) / (2 * X * Y))
    out = sp.expand(sp.expand(out) * X * Y * R)      # Jacobian X Y R
    num, den = sp.fraction(sp.together(out))
    for s in (X, Y, R):
        assert not den.has(s), ('negative power survives', den)
    return out

def integrate(expr):
    ex = sp.Poly(sp.expand(expr.subs({X: p + q, Y: p + r, R: q + r})), p, q, r)
    out = 0
    for (i, j, k), cf in ex.terms():
        out += 2 * cf * sp.factorial(i) * sp.factorial(j) * sp.factorial(k) * u**(i + 1) * wq**(j + 1) * v**(k + 1)
    return out

results = {}
for tb in names:
    for tk in names:
        Pb, Pk = types[tb], types[tk]
        S_int = sum(Pb[n] * Pk[n] for n in range(len(Pb)))
        T_int = 0
        for n in range(len(Pb)):
            gxb, gyb = grads(Pb[n], a, b, c)
            gxk, gyk = grads(Pk[n], d, e, g)
            T_int += sp.Rational(1, 2) * (w1 * dot(gxb, gxk) + w2 * dot(gyb, gyk) + w3 * (dot(gxb, gyk) + dot(gyb, gxk)))
        V_int = S_int * (q13 / X + q23 / Y + q12 / R)
        S = integrate(reduce_scalar(S_int))
        H = integrate(reduce_scalar(T_int + V_int))
        results[(tb, tk)] = (sp.expand(S), sp.expand(H))
        print('done', tb, tk, len(sp.Add.make_args(results[(tb, tk)][1])), file=sys.stderr)

# common integer scale
import math
den = 1
for S, H in results.values():
    for ex in (S, H):
        for term in sp.Add.make_args(ex):
            cf = term.as_coeff_Mul()[0]
            den = math.lcm(den, sp.Rational(cf).q)
print('scale', den, file=sys.stderr)

from sympy.printing.cxx import CXX11CodePrinter
class P(CXX11CodePrinter):
    def _print_Pow(self, ex):
        bse, ex_ = ex.args
        assert ex_.is_Integer and ex_ > 0, ex
        s = self._print(bse)
        if not bse.is_Symbol:
            s = '(' + s + ')'
        return '(' + '*'.join([s] * int(ex_)) + ')'
    def _print_Integer(self, ex):
        return '%dL' % int(ex)
    def _print_Rational(self, ex):
        raise ValueError('rational left: %s' % ex)
pr = P()
out = ['// generated by gen.py %d; do not edit' % L, '#define SCALE_L%d %d' % (L, den),
       'static const char* TYPES_L%d[] = {%s};' % (L, ','.join('"%s"' % n for n in names))]
for (tb, tk), (S, H) in results.items():
    S2, H2 = sp.expand(S * den), sp.expand(H * den)
    # Horner-like grouping in u, wq, v helps cse
    S2 = sp.collect(S2, [u, wq, v]); H2 = sp.horner(H2, u, wq, v, wrt=None) if False else H2
    reps, (Sx, Hx) = sp.cse([S2, H2], symbols=sp.numbered_symbols('t'), optimizations='basic')
    out.append('template<class T> static void el_L%d_%s_%s(const T&a,const T&b,const T&c,const T&d,const T&e,const T&g,'
               'const T&u,const T&wq,const T&v,const T&w1,const T&w2,const T&w3,const T&q13,const T&q23,const T&q12,T&S,T&H){' % (L, tb, tk))
    for sym, ex in reps:
        out.append('  T %s = %s;' % (sym, pr.doprint(ex)))
    out.append('  S = %s;' % pr.doprint(Sx))
    out.append('  H = %s;' % pr.doprint(Hx))
    out.append('}')
out.append('template<class T> static void el_L%d(int tb,int tk,const T&a,const T&b,const T&c,const T&d,const T&e,const T&g,'
           'const T&u,const T&wq,const T&v,const T&w1,const T&w2,const T&w3,const T&q13,const T&q23,const T&q12,T&S,T&H){' % L)
out.append('  switch(tb*%d+tk){' % len(names))
for i, tb in enumerate(names):
    for j, tk in enumerate(names):
        out.append('    case %d: el_L%d_%s_%s(a,b,c,d,e,g,u,wq,v,w1,w2,w3,q13,q23,q12,S,H); break;' % (i * len(names) + j, L, tb, tk))
out.append('  }\n}')
open('elems_L%d.h' % L, 'w').write('\n'.join(out) + '\n')
# also a pickle of the symbolic results for the Python cross-checks
import pickle
pickle.dump({k: (str(S), str(H)) for k, (S, H) in results.items()}, open('elems_L%d.pkl' % L, 'wb'))
