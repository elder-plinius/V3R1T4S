# Generates LebVerifyI/IvConsts.cs : outward double enclosures [lo,hi] of every real constant used on the leaf path.
# Real values come from mpmath.iv (rigorous interval arithmetic, 70 digits) or exact Fractions; conversion double<-Fraction is exact floor/ceil.
import math, struct
from fractions import Fraction
from mpmath import iv, mp
mp.dps = 70; iv.dps = 70

def bits(d): return struct.unpack('<q', struct.pack('<d', d))[0]
def dn(fr):
    d = float(fr)                      # nearest (Python int/int true division is correctly rounded)
    while Fraction(d) > fr: d = math.nextafter(d, -math.inf)
    return d
def up(fr):
    d = float(fr)
    while Fraction(d) < fr: d = math.nextafter(d, math.inf)
    return d
def mpf2fr(t):   # t = raw mpf tuple (sign, man, exp, bc)
    s = -1 if t[0] else 1
    return s * Fraction(int(t[1])) * (Fraction(2) ** int(t[2]))
def enc_iv(v):  # v: mpmath iv value
    return dn(mpf2fr(v._mpi_[0])), up(mpf2fr(v._mpi_[1]))
def enc_fr(fr): return dn(fr), up(fr)
def cs(d): return "BitConverter.Int64BitsToDouble(unchecked((long)0x%016XUL))" % (struct.unpack('<Q', struct.pack('<d', d))[0])
def ivc(pair): return "new Iv(%s, %s)" % (cs(pair[0]), cs(pair[1]))

out = []
out.append("// GENERATED by gen_ivconsts.py (mpmath.iv at 70 digits / exact Fractions). Every constant is an outward enclosure [lo,hi]; doubles given by raw bit patterns (no decimal parsing).")
out.append("using System;")
out.append("namespace LebVerify { public static class IvConsts {")
pi = iv.pi
out.append("  public static readonly Iv Pi = %s;" % ivc(enc_iv(pi)))
s3 = iv.sqrt(3)
V3x = [1/s3, -1/(2*s3), -1/(2*s3)]
out.append("  public static readonly Iv[] V3x0 = { %s };" % ", ".join(ivc(enc_iv(v)) for v in V3x))
out.append("  public static readonly Iv[] V3y0 = { %s };" % ", ".join(ivc(enc_fr(Fraction(f))) for f in (0, Fraction(1,2), Fraction(-1,2))))
R5 = 1/(2*iv.sin(2*pi/5))
cx = [R5*iv.cos(2*pi*k/5) for k in range(5)]
cy = [R5*iv.sin(2*pi*k/5) for k in range(5)]
# exact special values: y1 = R5 sin72 = 1/2 ; y4 = -1/2 ; y0 = 0 ; x0 = R5
cyv = [ivc(enc_fr(Fraction(0))), ivc(enc_fr(Fraction(1,2))), ivc(enc_iv(cy[2])), ivc(enc_iv(cy[3])), ivc(enc_fr(Fraction(-1,2)))]
out.append("  public static readonly Iv[] V5x0 = { %s };" % ", ".join(ivc(enc_iv(v)) for v in cx))
out.append("  public static readonly Iv[] V5y0 = { %s };" % ", ".join(cyv))
out.append("  public static readonly Iv R5 = %s;   // circumradius 1/(2 sin 72deg) of the unit-width Reuleaux pentagon" % ivc(enc_iv(R5)))
out.append("  // 1/n! for n=0..30")
out.append("  public static readonly Iv[] InvFact = { %s };" % ", ".join(ivc(enc_fr(Fraction(1, math.factorial(n)))) for n in range(31)))
out.append("} }")
open('LebVerifyI/IvConsts.cs','w').write("\n".join(out)+"\n")
