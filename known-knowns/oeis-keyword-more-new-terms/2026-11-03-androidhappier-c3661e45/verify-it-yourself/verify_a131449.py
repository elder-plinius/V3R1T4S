"""Standalone checker for OEIS A131449 rows 0..6 (Python 3 standard library only).

Definition (A131449 %N): row n lists, for each of the Catalan(n) rooted ordered (plane) trees with n non-root
vertices, the number of organic (increasing) labelings: the root gets label 0, the non-root vertices get labels
1..n, and labels increase along every path from the root.  Rows are listed in non-increasing order (as every
row 0..5 of DATA is).

Method here (written for this package; neither the hook formula of Program A nor the removal-order DP of
Program B): trees are nested tuples, generated by "first child subtree + remaining forest"; the labelings of a
forest of subtrees with sizes s_1..s_k are counted recursively as the multinomial (s_1+..+s_k)!/(s_1!..s_k!) times
the product of the subtrees' own counts (a subtree's root takes the smallest label of its block).

usage: python3 verify_a131449.py OBJECT_ROW6 OBJECT_VALUE      -> checks, exit 0 on success
       python3 verify_a131449.py --control                      -> negative control (labels only need to differ
                                                                  from the parent's); exit 0 iff it reproduces DATA
"""
import sys
from math import factorial
from functools import lru_cache

# OEIS A131449 DATA, indices 0..65 (offset 0), as of 2026-11-03 (%I #12 Aug 29 2019)
DATA = [1,1,2,1,6,3,3,2,1,24,12,12,12,8,8,6,6,4,4,3,3,2,1,120,60,60,60,60,40,
        40,40,30,30,30,30,30,24,20,20,20,20,20,15,15,15,15,12,12,12,10,10,10,
        10,8,8,6,6,5,5,4,4,3,3,2,1,720]

@lru_cache(maxsize=None)
def forests(n):
    """All ordered forests with n vertices, each a tuple of trees; a tree is the tuple of its child trees."""
    if n == 0:
        return ((),)
    out = []
    for k in range(1, n + 1):           # first tree has k vertices: its root + a forest of k-1 below it
        for below in forests(k - 1):
            for rest in forests(n - k):
                out.append((below,) + rest)
    return tuple(out)

def size(t):
    return 1 + sum(size(c) for c in t)

def count_forest(f, control=False):
    """Increasing labelings of a forest (each tree root is free relative to the others)."""
    sizes = [size(t) for t in f]
    total = factorial(sum(sizes))
    for s in sizes:
        total //= factorial(s)
    for t in f:
        total *= count_tree(t, control)
    return total

def count_tree(t, control=False):
    # root of t takes the smallest label of its block; its children form a forest on the rest
    if control:
        # control: drop "increasing" -- any assignment of the block's labels counts
        return factorial(size(t))
    return count_forest(t, control)

def rows(nmax, control=False):
    flat, out = [], []
    for n in range(nmax + 1):
        # a rooted ordered tree with n non-root vertices = an ordered forest with n vertices below the root
        row = sorted((count_forest(f, control) for f in forests(n)), reverse=True)
        out.append(row)
        flat.extend(row)
    return out, flat

def catalan(n):
    return factorial(2 * n) // (factorial(n) * factorial(n + 1))

def dfact(n):  # (2n-1)!!
    r = 1
    for k in range(1, 2 * n, 2):
        r *= k
    return r

def main():
    if len(sys.argv) > 1 and sys.argv[1] == "--control":
        _, flat = rows(6, control=True)
        print("control rows 0..5 first 15:", flat[:15])
        return 0 if flat[:66] == DATA else 1
    obj6, objv = sys.argv[1], sys.argv[2]
    rs, flat = rows(6)
    ok = True
    for n, row in enumerate(rs):
        print("%d len=%d sum=%d head: %s" % (n, len(row), sum(row), ",".join(map(str, row[:12]))))
        if len(row) != catalan(n) or sum(row) != dfact(n):
            print("row %d: length or sum wrong (want Catalan %d, (2n-1)!! %d)" % (n, catalan(n), dfact(n)))
            ok = False
    # sanity on single trees: star with 6 children = 720, path = 1, two cherries under the root = 80
    star = ((),) * 6
    path = ((((((),),),),),)
    cherries = (((), ()), ((), ()))
    sane = (count_forest(star), count_forest(path), count_forest(cherries)) == (720, 1, 80)
    print("single-tree sanity star/path/two cherries = %s" % ("720/1/80 ok" if sane else "WRONG"))
    ok = ok and sane
    if flat[:66] == DATA:
        print("indices 0..65 equal OEIS DATA (66 terms)")
    else:
        print("indices 0..65 DIFFER from OEIS DATA"); ok = False
    want = [int(x) for x in open(obj6).read().strip().split(",")]
    if rs[6] == want and flat[65:197] == want:
        print("row 6 (132 values, flattened indices 65..196) equals %s" % obj6)
    else:
        print("row 6 differs from %s" % obj6); ok = False
    v = int(open(objv).read().strip())
    if flat[66] == v == 360:
        print("index 66 = T(6,2) = %d equals %s" % (flat[66], objv))
    else:
        print("index 66 = %d, object says %d" % (flat[66], v)); ok = False
    return 0 if ok else 1

if __name__ == "__main__":
    sys.exit(main())
