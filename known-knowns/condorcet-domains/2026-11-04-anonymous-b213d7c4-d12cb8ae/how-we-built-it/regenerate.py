"""Faithful replay of the frozen successful search, with fresh relative caps.
Run from the package root, with a NEW output directory outside this package.
No run-absolute deadline is embedded. No change to the native search algorithm.
"""
from pathlib import Path
import argparse, datetime, hashlib, json, os, resource, shutil, subprocess, time

ap=argparse.ArgumentParser();ap.add_argument('output',type=Path);a=ap.parse_args()
root=Path.cwd().resolve();out=a.output.resolve()
if out==root or root in out.parents:raise SystemExit('Use a new output directory outside the package')
out.mkdir(parents=True,exist_ok=False)
src=root/'how-we-built-it';compiler=shutil.which('c++')
if not compiler:raise SystemExit('A C++17 compiler is required')
expected={'source-assignment.txt':'be05fe9ea7f4f6f33777cdf17e1c97d5d6869419838005b0ca949adca6fc2483','marginal-alternatives.csv':'5f710c7fab5f7340d71365d52bc625e1474c6d09d71610c34fb4fc32f87cfc79'}
for name,h in expected.items():
    if hashlib.sha256((src/name).read_bytes()).hexdigest()!=h:raise SystemExit('Frozen input hash mismatch: '+name)
def run(cmd,cap):
    def limits():
        resource.setrlimit(resource.RLIMIT_CPU,(cap,cap+1))
        try:os.nice(10)
        except PermissionError:pass # this fixed replay was measured as <1s; still strictly foreground/capped
    p=subprocess.Popen(cmd,stdout=subprocess.PIPE,stderr=subprocess.STDOUT,text=True,preexec_fn=limits)
    with (out/'processes.jsonl').open('a') as f:f.write(json.dumps(dict(event='launch',utc=datetime.datetime.now(datetime.timezone.utc).isoformat(),pid=p.pid,argv=cmd,nice=os.getpriority(os.PRIO_PROCESS,p.pid),relative_cpu_cap=cap,relative_wall_cap=cap+5))+'\n')
    try:stdout,_=p.communicate(timeout=cap+5)
    except subprocess.TimeoutExpired:p.kill();stdout,_=p.communicate();raise
    with (out/'replay.log').open('a') as f:f.write(stdout)
    with (out/'processes.jsonl').open('a') as f:f.write(json.dumps(dict(event='terminal',utc=datetime.datetime.now(datetime.timezone.utc).isoformat(),pid=p.pid,waited=True,returncode=p.returncode))+'\n')
    if p.returncode:raise SystemExit('Replay stage failed: '+str(p.returncode))
run([compiler,'-std=c++17','-O3','-Wall','-Wextra','-Werror=return-type',str(src/'marginal_dag.cpp'),'-o',str(out/'search')],30)
run([str(out/'search'),str(src/'source-assignment.txt'),str(src/'marginal-alternatives.csv'),'1000000',str(out),'1000000','search'],30)
